import shim; shim.reset()
A = shim.A; c = A.app.test_client()
def j(r): return r.get_json()
ok = lambda cond, m: print(('OK   ' if cond else 'FALLA'), m) or (cond or (_ for _ in ()).throw(SystemExit(1)))
ok(c.get('/api/cursos').status_code == 401, 'API protegida sin sesión -> 401')
ok(c.get('/dashboard').status_code == 302, 'Página protegida redirige')
ok(j(c.get('/api/normativas'))['ok'] and len(j(c.get('/api/normativas'))['normativas']) == 6, 'Normativas públicas (6)')
ok(len(j(c.get('/api/normativas?q=plagio'))['normativas']) == 1, 'Búsqueda "plagio" -> 1')
ok(len(j(c.get('/api/normativas?categoria=Privacidad'))['normativas']) == 2, 'Filtro por categoría -> 2')
r = c.post('/api/registro', json={'nombre_completo': 'Saúl Prueba', 'correo': 'S@Correo.com', 'contrasena': 'abc123', 'confirmar_contrasena': 'abc123'})
ok(r.status_code == 201 and j(r)['ok'], 'Registro (201) y correo en minúsculas')
ok(c.post('/api/registro', json={'nombre_completo': 'X', 'correo': 's@correo.com', 'contrasena': 'abc123'}).status_code == 409, 'Correo duplicado -> 409')
ok(c.post('/api/registro', json={'nombre_completo': 'X', 'correo': 'malo', 'contrasena': 'abc123'}).status_code == 400, 'Correo inválido -> 400')
ok(c.post('/api/registro', json={'nombre_completo': 'X', 'correo': 'a@b.co', 'contrasena': '123'}).status_code == 400, 'Contraseña corta -> 400')
ok(c.post('/api/registro', json={'nombre_completo': 'X', 'correo': 'a@b.co', 'contrasena': 'x'*80}).status_code == 400, 'Contraseña >72 bytes -> 400')
row = A.get_db().cursor(dictionary=True).execute('SELECT contrasena_hash FROM usuarios').fetchone()
ok(row['contrasena_hash'].startswith('$2b$'), 'Contraseña guardada con bcrypt')
me = j(c.get('/api/me'))['usuario']
ok(me['nombre_completo'] == 'Saúl Prueba' and me['porcentaje_global'] == 0 and me['lecciones_total'] == 8 and me['cursos_total'] == 3, 'api/me: sesión tras registro, 8 lecciones, 3 cursos')
cur = j(c.get('/api/cursos'))['cursos']
ok(len(cur) == 3 and cur[0]['total_lecciones'] == 3 and cur[0]['completadas'] == 0, 'Cursos con progreso')
ok(len(j(c.get('/api/cursos/1'))['lecciones']) == 3, 'Detalle de curso')
l = j(c.get('/api/lecciones/2'))['leccion']
ok(l['anterior'] == 1 and l['siguiente'] == 3 and not l['completada'], 'Lección 2: anterior=1, siguiente=3')
ok(j(c.get('/api/siguiente-leccion'))['leccion']['id_leccion'] == 1, 'Siguiente lección = 1')
for i in (1, 2, 3):
    r = j(c.post(f'/api/lecciones/{i}/completar', json={'completada': True}))
ok(r['progreso']['porcentaje_global'] == 37.5 and r['progreso']['cursos_completados'] == 1, 'Completar curso 1: 3/8 = 37.5%, 1 curso')
ok(j(c.get('/api/siguiente-leccion'))['leccion']['id_leccion'] == 4, 'Siguiente lección = 4')
r = j(c.post('/api/lecciones/3/completar', json={'completada': False}))
ok(r['progreso']['porcentaje_global'] == 25.0 and r['progreso']['cursos_completados'] == 0, 'Desmarcar: 25%, 0 cursos')
ok(c.post('/api/lecciones/999/completar', json={}).status_code == 404, 'Lección inexistente -> 404')
j(c.get('/api/normativas/1')); j(c.get('/api/normativas/1')); j(c.get('/api/normativas/2'))
ok(j(c.get('/api/me'))['usuario']['normas_consultadas'] == 2, 'Normas consultadas = 2 distintas')
ok(c.get('/api/normativas/999').status_code == 404, 'Norma inexistente -> 404')
r = c.put('/api/perfil', json={'nombre_completo': 'Saúl A.', 'institucion': 'ITM', 'biografia': 'Hola', 'contrasena_nueva': 'nueva123'})
ok(j(r)['ok'], 'Actualizar perfil + contraseña')
me = j(c.get('/api/me'))['usuario']; ok(me['institucion'] == 'ITM' and me['nombre_completo'] == 'Saúl A.', 'Perfil guardado')
ok(j(c.post('/api/logout'))['ok'] and c.get('/api/me').status_code == 401, 'Cerrar sesión')
ok(c.post('/api/login', json={'correo': 's@correo.com', 'contrasena': 'abc123'}).status_code == 401, 'Contraseña vieja rechazada')
ok(c.post('/api/login', json={'correo': 'no@existe.com', 'contrasena': 'abc123'}).status_code == 401, 'Usuario inexistente -> 401')
ok(j(c.post('/api/login', json={'correo': 'S@correo.com ', 'contrasena': 'nueva123'}))['ok'], 'Login con contraseña nueva')
ok(c.get('/api/logout').status_code == 405, 'Logout por GET no permitido')
print('\nTODAS LAS PRUEBAS DE API PASARON')
